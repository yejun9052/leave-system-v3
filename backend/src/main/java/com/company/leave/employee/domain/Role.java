package com.company.leave.employee.domain;

/**
 * 사용자 권한(역할). Spring Security 에서는 {@code ROLE_} 접두사를 붙여 사용한다.
 * 역할 간 상속은 없다: 상위 역할이 하위 역할의 권한을 자동으로 갖지 않으며, 필요한 역할을 각각 부여한다.
 */
public enum Role {
    /**
     * 시스템 관리자 — 관리 전용 계정(admin, system_account)에만 부여. 일반 직원에게는 줄 수 없다(V18).
     * 관리 기능(사용자·부서·정책·휴가 종류·공휴일·연차 부여·리포트·이벤트 로그)은 쓸 수 있지만,
     * 직원이 아니므로 휴가 신청·결재(1차·최종·취소 결재)는 하지 않는다. 다른 역할과 함께 있어도 결재 불가.
     */
    SYSTEM_ADMIN,
    /**
     * 인사 관리자 — 사용자·부서·정책 운영, 휴가 최종 결재(인사 단계)와 승인된 휴가의 취소 결재.
     * 본인 휴가는 팀장 단계 없이 인사 단계로 가며 스스로 승인할 수 있다. 팀장 단계 건은 대신 결재하지 않는다.
     */
    HR_ADMIN,
    /**
     * 팀장 — 담당 부서(하위 부서 포함) 팀원 휴가의 1차 결재, 팀 일정 등록.
     * 본인 휴가는 인사관리자가 결재하고, 취소 결재는 하지 않는다(취소 확정 시 알림만 받음).
     */
    TEAM_LEAD,
    /** 사원 — 휴가 신청·조회·취소 요청 */
    EMPLOYEE;

    public String authority() {
        return "ROLE_" + name();
    }
}
